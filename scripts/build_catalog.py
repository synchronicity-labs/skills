#!/usr/bin/env python3
"""Write catalog.json: the machine-readable list of skills that Studio, the docs and other
consumers read from GitHub, so they update when this repo does.

  python3 scripts/build_catalog.py          # write catalog.json
  python3 scripts/build_catalog.py --check  # fail if catalog.json is stale (CI)

Published at https://raw.githubusercontent.com/synchronicity-labs/skills/main/catalog.json
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REPO = "synchronicity-labs/skills"
DOCS = "https://sync.so/docs/plugins-and-extensions/agent-skills"
# Display order: getting started, single-video workflows, many videos, developers, recovery.
ORDER = ["setup", "lipsync", "talking-photo", "ai-video-to-talking", "translate-and-dub", "edit-dialogue",
         "localize-campaign", "batch-lipsync", "sync-api", "troubleshoot"]


def frontmatter(text: str) -> dict:
    block = re.match(r"^---\n(.*?)\n---\n", text, re.S).group(1)
    return {k.strip(): v.strip() for k, v in (line.split(":", 1) for line in block.splitlines() if ":" in line and not line.startswith(" "))}


def openai_yaml(path: Path) -> dict:
    fields = {}
    for line in path.read_text().splitlines():
        match = re.match(r'^\s+(display_name|short_description|default_prompt):\s*"(.*)"\s*$', line)
        if match:
            fields[match.group(1)] = match.group(2)
    return fields


def build() -> str:
    plugin = json.loads((ROOT / ".claude-plugin" / "plugin.json").read_text())
    names = sorted(p.parent.name for p in (ROOT / "skills").glob("*/SKILL.md"))
    unordered = [n for n in names if n not in ORDER]
    if unordered:
        sys.exit(f"Add these skills to ORDER in scripts/build_catalog.py: {', '.join(unordered)}")
    skills = []
    for name in [n for n in ORDER if n in names]:
        fm = frontmatter((ROOT / "skills" / name / "SKILL.md").read_text())
        ui = openai_yaml(ROOT / "skills" / name / "agents" / "openai.yaml")
        skills.append({
            "name": name,
            "displayName": ui["display_name"],
            "summary": ui["short_description"],
            "description": fm["description"],
            "guideUrl": f"{DOCS}/{name}",
            "sourceUrl": f"https://github.com/{REPO}/tree/main/skills/{name}",
            "install": f"npx skills add {REPO} --skill {name}",
        })
    catalog = {
        "$comment": "Generated by scripts/build_catalog.py. Edit the skills, not this file.",
        "version": plugin["version"],
        "repository": f"https://github.com/{REPO}",
        "docsUrl": f"{DOCS}/overview",
        "install": {
            "skills": f"npx skills add {REPO}",
            "claudeCode": [f"/plugin marketplace add {REPO}", "/plugin install sync@sync", "/mcp"],
        },
        "mcpServer": json.loads((ROOT / ".mcp.json").read_text())["mcpServers"]["sync"]["url"],
        "skills": skills,
    }
    return json.dumps(catalog, indent=2, ensure_ascii=False) + "\n"


def main() -> int:
    out = ROOT / "catalog.json"
    text = build()
    if "--check" in sys.argv:
        if not out.exists() or out.read_text() != text:
            print("catalog.json is stale; run python3 scripts/build_catalog.py")
            return 1
        return 0
    out.write_text(text)
    print(f"wrote catalog.json with {len(json.loads(text)['skills'])} skills")
    return 0


if __name__ == "__main__":
    sys.exit(main())
